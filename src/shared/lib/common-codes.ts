/** 해당 그룹의 코드명 조회. 미등록 코드는 원본 값을 반환합니다. */
export function getG2bCommonCodeName(
  group: string,
  code: string | null | undefined,
): string {
  if (code == null || code === "") return "";
  const codes: Readonly<Record<string, Readonly<Record<string, string>>>> =
    G2B_COMMON_CODES;
  return codes[group]?.[code] ?? code;
}

/** 공통코드 분류와 업무 분류를 각각 전달하는 경우. */
export function getG2bCommonCodeNameByClassification(
  commClsfCd: string,
  bsneClsfNo: string,
  code: string | null | undefined,
): string {
  return getG2bCommonCodeName(`${commClsfCd}_${bsneClsfNo}`, code);
}
